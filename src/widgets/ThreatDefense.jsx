import { useState } from 'react'

// Відповідність загроза -> механізм захисту. Логіку звірено threat_test.mjs.
const CONTROLS = {
  crypt: { label: 'Шифрування (TLS / DLMS ciphering)', short: 'Шифрування' },
  mac:   { label: 'HMAC / цифровий підпис', short: 'HMAC/підпис' },
  fresh: { label: 'Свіжість: nonce / мітка часу / лічильник', short: 'Nonce/ts' },
  auth:  { label: 'Взаємна автентифікація (HLS, ключі, сертифікати)', short: 'Взаємна авт.' },
  avail: { label: 'Доступність: резервування, rate-limit, watchdog', short: 'Резервування' },
  seal:  { label: 'Пломби + журнал подій втручання (tamper log)', short: 'Пломби/tamper' },
}
const THREATS = {
  eavesdrop: { label: 'Перехоплення показів', goal: 'Конфіденційність', controls: ['crypt'],
    note: 'Пасивний зловмисник читає трафік. HMAC тут не допомагає — він не приховує значення. Потрібне шифрування каналу (TLS над MQTT/HTTP або вбудоване шифрування DLMS/COSEM).' },
  tamper: { label: 'Підміна значень у каналі', goal: 'Цілісність', controls: ['mac'],
    note: 'Активний зловмисник змінює показ у дорозі. Ловить код автентифікації (HMAC) або цифровий підпис — приймач бачить, що підпис не збігається (саме це ви зробили в ЛР6).' },
  spoof: { label: 'Підробка джерела (spoofing лічильника)', goal: 'Автентичність', controls: ['auth', 'mac'],
    note: 'Зловмисник видає себе за легітимний лічильник. Основа — взаємна автентифікація (HLS/сертифікати); HMAC на секретному ключі дає базову автентичність джерела, бо підпис може створити лише власник ключа.' },
  replay: { label: 'Повтор старого пакета (replay)', goal: 'Свіжість', controls: ['fresh', 'mac'],
    note: 'Валідний підписаний пакет надсилають повторно. HMAC його пропустить — підпис-бо чинний. Потрібна свіжість: мітка часу / nonce / лічильник послідовності, які приймач перевіряє (додаток у кроці 5 ЛР6).' },
  dos: { label: 'Відмова в обслуговуванні (DoS / глушіння)', goal: 'Доступність', controls: ['avail'],
    note: 'Мета — не підмінити, а позбавити даних. Криптографія не рятує. Потрібні резервні канали, обмеження швидкості, буферизація показів у лічильнику та сторожові таймери (watchdog).' },
  physical: { label: 'Фізичне втручання в лічильник', goal: 'Виявлення втручання', controls: ['seal'],
    note: 'Відкриття клемної кришки, магніт, шунт. Захист — не в каналі: пломби, датчики розкриття, реєстрація подій втручання (tamper) самим лічильником з подальшим алертом (Л10).' },
}

export default function ThreatDefense() {
  const [t, setT] = useState('tamper')
  const th = THREATS[t]
  const active = new Set(th.controls)

  return (
    <div className="widget">
      <h3>🔐 Яка загроза — який захист?</h3>
      <p className="hint">
        Жоден єдиний механізм не закриває всі загрози: шифрування ховає, але не гарантує цілісності; HMAC гарантує
        цілісність, але не ховає й не спиняє повтор. Оберіть загрозу — побачите, яка <b>властивість безпеки</b> під
        ударом і які <b>механізми</b> її захищають.
      </p>

      <div className="tabs">
        {Object.entries(THREATS).map(([k, v]) => (
          <button key={k} className={`tab ${t === k ? 'active' : ''}`} onClick={() => setT(k)}>{v.label.split(' (')[0]}</button>
        ))}
      </div>

      <p style={{ margin: '10px 0 4px' }}>
        Під загрозою <b>«{th.label}»</b> — властивість <b>{th.goal}</b>. Захищають:
      </p>
      <table className="data">
        <thead><tr><th>Механізм захисту</th><th>Застосовний?</th></tr></thead>
        <tbody>
          {Object.entries(CONTROLS).map(([k, c]) => (
            <tr key={k} style={{ fontWeight: active.has(k) ? 700 : 400, opacity: active.has(k) ? 1 : 0.5 }}>
              <td>{c.label}</td>
              <td>{active.has(k) ? '✓ так' : '—'}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <p className="verdict ok" style={{ marginTop: 8 }}>{th.note}</p>
      <p className="hint">
        Це відображення властивостей <b>CIA</b> (конфіденційність / цілісність / доступність) плюс автентичність і
        свіжість на конкретні механізми. У реальних системах обліку їх поєднують: DLMS/COSEM security suite
        (автентифікація + шифрування), TLS на транспорті, мітки часу проти повтору, пломби й tamper-журнал проти фізики.
      </p>
    </div>
  )
}
