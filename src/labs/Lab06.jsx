const CHANNEL = `# channel.py — автентичність показів у каналі обліку через HMAC-SHA256. Лише stdlib (hmac, hashlib).
# Ідея: лічильник підписує кожен запис секретним ключем; приймач (білінг) перевіряє підпис.
# Підміна значення в каналі робить підпис недійсним -> білінг відхиляє запис.
import hmac, hashlib

KEY = b"shared-meter-key-0xA1B2"          # спільний секрет лічильник<->сервер (у реалі - в захищеному сховищі)

def sign(ts, kwh):                         # лічильник: формує підпис
    msg = f"{ts}|{kwh:.2f}".encode()
    return hmac.new(KEY, msg, hashlib.sha256).hexdigest()

def verify(ts, kwh, tag):                  # сервер: перевіряє (constant-time порівняння)
    return hmac.compare_digest(sign(ts, kwh), tag)

# --- легітимна передача ---
ts, kwh = 1734000000, 123.45
tag = sign(ts, kwh)
pkt = {"ts": ts, "kwh": kwh, "hmac": tag}
print("лічильник передає:", pkt)
print("білінг приймає:  ", "ПРИЙНЯТО" if verify(pkt["ts"], pkt["kwh"], pkt["hmac"]) else "ВІДХИЛЕНО")

# --- атака 1: зловмисник у каналі занижує показ, підпис не чіпає ---
tampered = dict(pkt); tampered["kwh"] = 90.00
print("\\nпідмінений пакет:", tampered)
ok = verify(tampered["ts"], tampered["kwh"], tampered["hmac"])
print("білінг приймає:  ", "ПРИЙНЯТО" if ok else "ВІДХИЛЕНО (підпис не збігається)")

# --- атака 2: зловмисник підробляє і значення, і підпис, але не знає ключа ---
forged = dict(pkt); forged["kwh"] = 90.00
forged["hmac"] = hmac.new(b"wrong-key", f'{forged["ts"]}|{forged["kwh"]:.2f}'.encode(), hashlib.sha256).hexdigest()
print("\\nпідроблений підпис (без ключа):", forged["hmac"][:16], "...")
print("білінг приймає:  ", "ПРИЙНЯТО" if verify(forged["ts"], forged["kwh"], forged["hmac"]) else "ВІДХИЛЕНО (немає секретного ключа)")
`

